    // ==================== 长期记忆 ====================

    /**
     * 长期记忆抽取提示词（LongTermMemoryManager 使用）。
     * 从一次会话的完整 transcript 中抽取可跨会话复用的事实。
     */
    public static final String MEMORY_EXTRACT_PROMPT = """
            你是一个跨会话长期记忆抽取助手。从一次 Agent 调用的完整对话记录中，抽取值得在未来会话中保留的事实。

            ## 应该抽取的内容
            - 用户身份、角色、技术栈、长期偏好与习惯
            - 项目级事实：架构、模块结构、关键类/文件/表名、版本、配置约束
            - 明确的决策及其原因（"为什么选 A 而不是 B"）
            - 用户明确要求"记住"的信息
            - 反复出现的业务规则、命名约定、约束条件

            ## 禁止抽取的内容
            - 一次性的查询、计算、翻译结果
            - 工具调用本身的过程或临时调试细节
            - 寒暄、闲聊、对未来会话无复用价值的中间状态
            - 从单次行为推断出的属性（如用户使用 Python 写脚本，不能推断为"Python 开发者"）
            - 任何对话中未直接出现的信息

            ## 严格规则
            1. 每条记忆必须独立可读、信息完整、尽可能全面且精炼的描述
            2. 用陈述句表述，不要用对话原文形式
            3. 同主题信息合并为一条，避免出现内容高度相似的多条
            4. 宁可漏抽，不可错抽；无可保留内容时返回空数组 []
            5. 最多输出 3 条

            ## 输出格式
            返回 JSON 字符串数组，每个元素是一条记忆：
            ["记忆1", "记忆2"]

            只返回 JSON 数组，不要包含其他文字。""";

    /**
     * 长期记忆合并提示词（LongTermMemoryManager 使用）。
     * 将新抽取的记忆与向量库中检索到的相似记忆合并为一条。
     */
    public static final String MEMORY_MERGE_PROMPT = """
            你是一个长期记忆合并助手。将一条【新记忆】与一条或多条【已有相似记忆】合并为一条无冲突的完整表述。

            ## 合并规则
            1. 新记忆与已有记忆存在矛盾时，以新记忆为准（视为用户变更了事实）
            2. 信息互补时合并为一条更完整的描述
            3. 已有记忆中未被新记忆覆盖的部分要保留
            4. 严禁添加任何输入中不存在的信息
            5. 严禁从已有记忆推断新事实
            6. 合并后输出一条独立可读的陈述，长度不超过单条记忆长度的 2 倍

            ## 输出格式
            直接返回合并后的记忆文本（纯文本，不要 JSON、不要 Markdown、不要解释）。""";

    // ==================== 上下文压缩 ====================

    /**
     * 历史轮次摘要提示词（HistoricalRoundSummaryStrategy / L4 使用）。
     * 将较早的历史轮次压缩为结构化摘要，使后续模型无需阅读完整历史也能恢复会话状态。
     */
    public static final String SESSION_SUMMARIZATION_PROMPT = """
            你是一个长期会话记忆压缩助手。

            你会收到以下两种情况之一：
            1. 仅「本轮新增对话」—— 这是首次压缩，请直接生成摘要。
            2. 「已有会话摘要」+「本轮新增对话」—— 需要将新增对话合并到已有摘要中，
               更新并输出一份完整的会话摘要（保持原有内容中仍有效的部分，补充新增信息）。

            你的任务是生成一份长期会话摘要，使后续模型无需阅读完整历史，也能快速恢复会话状态，理解此前讨论的背景、过程、决策及当前进展，并自然继续当前会话。

            ## 保留内容

            - 每个讨论主题最初提出的问题、目标或需求。
            - 每个主题的重要讨论过程、核心观点及关键细节。
            - 如果方案发生调整，保留方案演进过程（初始方案、调整原因、最终方案）。
            - 已确认的结论、决策，以及仍未解决或待继续讨论的事项。
            - 用户明确表达的偏好、限制条件或需求变化。
            - 文件路径、URL、版本号、接口名、类名、方法名、表名等精确信息必须原样保留。

            ## 压缩原则

            - 严格保持时间顺序，体现会话的发展脉络。
            - 按主题归纳连续讨论，避免逐轮复述，但不要打乱主题出现的先后顺序。
            - 优先保留影响后续对话连续性的内容，而不是追求更高的压缩率。
            - 删除寒暄、重复表达、工具调用过程、中间推理及无关细节，仅保留有效信息。
            - 当新增内容仅包含 1~2 轮对话时，无需刻意压缩，保持原意即可。
            - 不要编造、推断或补充对话中不存在的信息。
            - 将整体内容控制在精简描述的范围内，禁止内容过大

            ## 输出要求

            - 使用清晰、易于阅读的 Markdown，根据内容自行组织结构。
            - 保持内容连贯，方便后续模型快速理解会话上下文。
            - 不使用固定模板，不为了满足格式而补充不存在的信息。
            - 不输出 JSON、XML 或代码块。
            """;

    /**
     * 上下文压缩摘要 - 系统提示词（ContextCompactor 使用）。
     */
    public static final String CONTEXT_COMPACT_SUMMARY_SYSTEM_PROMPT = """
            你是对话摘要助手。你的任务是将对话记录压缩为结构化摘要，使助手能**无缝接续**未完成的任务。

            ## 核心原则
            摘要的首要目标是**任务延续性**：阅读摘要的助手必须能准确理解当前进度，并指导助手下一步该做什么、调用什么工具。

            ## 必须保留的信息（不可省略）
            1. **用户意图**：原始请求的完整含义，不能丢失任何细节
            2. **文件路径、URL、变量名**等精确引用信息，原样保留
            3. **Skill 的核心步骤/规则**：已加载 Skill 的名称、描述、以及关键执行逻辑（不是完整内容，仅核心步骤）
            4. **已完成步骤的结论**：每个工具调用产生了什么结果，成功还是失败
            5. **下一步的具体操作**：明确指出接下来要调用什么工具、传什么参数、对什么文件操作

            ## 禁止事项
            - 禁止原样复制/粘贴完整对话内容，必须提炼压缩
            - 禁止输出思考过程
            - 禁止用模糊描述替代精确信息（如"操作了某个文件"应写明具体路径）

            ## 输出格式（严格按此结构）

            ### 一、历史对话摘要
            - 之前讨论过的主要话题和关键结论
            - 用户的偏好和关注点

            ### 二、当前任务执行摘要

            #### 1. 用户请求
            （完整保留用户意图的所有细节）

            #### 2. 已加载的 Skill
            - Skill 名称、描述
            - 核心执行步骤/关键规则（摘要形式，但必须包含执行逻辑）

            #### 3. 已完成的工具调用
            逐条列出每个工具调用：
            - 调用序号. 工具名称(关键参数摘要) → 结果：成功/失败 + 关键结论

            #### 4. 已获得的关键信息
            （从工具返回中提炼的所有重要数据/结论，用要点列出，精确信息原样保留）

            #### 5. 当前进度与下一步
            - **已完成**：简要概括当前进度
            - **下一步**：具体要执行什么操作（包含具体调什么工具）
            """;

    /**
     * 构建上下文压缩摘要的用户消息（指令 + 对话数据 + 当前请求）。
     *
     * @param conversationText 对话文本
     * @param currentQuestion  当前用户请求（可为 null）
     * @return 用户消息文本
     */
    public static String buildCompactSummaryUserPrompt(String conversationText, String currentQuestion) {
        return """
                请将以下对话记录压缩为结构化摘要。

                ## 当前用户请求
                %s

                ## 对话记录
                %s

                <no_think>
                """.formatted(
                currentQuestion != null && !currentQuestion.isBlank() ? currentQuestion : "无",
                conversationText != null ? conversationText : "无");
    }

    /**
     * 摘要合并系统提示词（ContextCompactor L4 使用）。
     * 将新生成的摘要与语义相关的已有摘要合并为更精炼的摘要。
     */
    public static final String SEMANTIC_SUMMARY_MERGE_PROMPT = """
            你是一个知识合并助手。你的任务是将一条【新摘要】与一条或多条【已有摘要】合并为一条更精炼的摘要。

            ## 合并规则
            1. 保留所有关键信息，去除重复部分
            2. 合并后的摘要应是一段完整的知识描述，独立可读
            3. 如果新摘要与已有摘要主题相同，合并为一条更全面的描述
            4. 不要添加任何原始内容中不存在的信息
            5. 合并后长度不应超过单条摘要长度的 2 倍

            ## 输入
            - 新摘要：一条新生成的知识摘要
            - 已有摘要：一条或多条主题相关的历史摘要

            ## 输出格式
            直接返回合并后的摘要文本（纯文本，不要 JSON，不要 markdown）。""";

    // ==================== 中断恢复 ====================

    /**
     * 中断恢复时追加的用户消息模板。
     * <p>
     * 将原始任务和用户在中断后的补充消息一起呈现，让 LLM 自行判断用户意图：
     * 是对原任务的调整、延续还是完全切换到新任务。
     */
    public static final String RESUME_INTERRUPT_USER_PROMPT = """
            [用户中断后返回]

            你之前的执行已被用户中断，以下是用户返回后发送的消息。
            请根据原始任务和用户消息之间的关系，判断用户意图并继续执行：
            - 如果用户是对原任务的细化或方向调整，请据此修正后续输出
            - 如果用户是提出新问题，请将其作为新任务处理
            - 如果用户只是让你继续，请无缝恢复执行

            原始任务：
            %s

            用户消息：
            %s
            """;

    /**
     * 构建中断恢复时的用户消息。
     *
     * @param originalQuery 中断前的原始任务
     * @param resumeQuery   中断后用户的补充消息
     * @return 格式化后的用户消息文本
     */
    public static String buildResumeInterruptMessage(String originalQuery, String resumeQuery) {
        return RESUME_INTERRUPT_USER_PROMPT.formatted(
                originalQuery != null ? originalQuery : "无",
                resumeQuery != null ? resumeQuery : "");
    }

    // ==================== 中断恢复 - 工具跳过 ====================

    /**
     * 中断恢复时工具被跳过的占位响应。
     * <p>
     * 当用户中断后带着新消息恢复，不再重新执行被中断的工具，
     * 而是注入此占位提示，让 LLM 根据用户的新指示自行决定下一步。
     */
    public static final String INTERRUPT_TOOL_SKIPPED_PROMPT = """
            工具执行被用户中断，用户返回后给出了新的指示。
            请根据用户补充的消息判断是否需要继续执行该工具，或调整方案。
            原工具调用：%s(%s)
            """;

    /**
     * 构建中断恢复时被跳过工具的占位响应。
     *
     * @param toolName  工具名称
     * @param arguments 工具参数 JSON
     * @return 格式化后的占位响应文本
     */
    public static String buildInterruptToolSkippedMessage(String toolName, String arguments) {
        return INTERRUPT_TOOL_SKIPPED_PROMPT.formatted(
                toolName != null ? toolName : "unknown",
                arguments != null ? arguments : "");
    }

